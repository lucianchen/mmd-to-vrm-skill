export function detectLanguage({requested, saved, languages = []} = {}) {
  const explicit = value => /^zh(?:-|$)/i.test(value || '') ? 'zh' : /^en(?:-|$)/i.test(value || '') ? 'en' : null;
  return explicit(requested) || explicit(saved) || explicit(languages[0]) || 'en';
}
export function translate(language, key, params = {}) {
  const value = translations[language]?.[key];
  if (typeof value !== 'string') throw new Error('Missing translation: '+language+'.'+key);
  return value.replace(/\{(\w+)\}/g, (_, name) => {
    if (!(name in params)) throw new Error('Missing translation argument: '+key+'.'+name);
    return String(params[name]);
  });
}
export class ViewerError extends Error {
  constructor(key, params = {}) { super(translate('en', key, params)); this.key = key; this.params = params; }
}
